-- Pasteboard helpers shared by the clipboard history and every tool that borrows the pasteboard
-- (reading the selection with ⌘C, pasting a snippet). Keeps secrets out and restores safely.
local Keep = require("keep")
local P = {}

-- Types password managers (and similar tools) put on the pasteboard to say "do not record this".
P.SECRET_TYPES = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
  ["com.agilebits.onepassword"] = true,
  ["de.petermaurer.TransientPasteboardType"] = true,
  ["com.typeit4me.clipping"] = true,
  ["net.antelle.keeweb"] = true,
  ["Pasteboard generator type"] = true,
}

-- Apps whose copies are never recorded, even if they forget to mark them.
P.SECRET_APPS = {
  ["com.apple.Passwords"] = true,
  ["com.apple.keychainaccess"] = true,
  ["com.bitwarden.desktop"] = true,
  ["com.1password.1password"] = true,
  ["com.agilebits.onepassword7"] = true,
  ["org.keepassxc.keepassxc"] = true,
}

function P.isSecret(types)
  for _, t in ipairs(types or {}) do
    if P.SECRET_TYPES[t] then return true end
  end
  return false
end

function P.currentIsSecret() return P.isSecret(hs.pasteboard.pasteboardTypes()) end

function P.frontAppIsSecret()
  local app = hs.application.frontmostApplication()
  return app ~= nil and P.SECRET_APPS[app:bundleID() or ""] == true
end

-- Only the main representations are saved: readAllData() would force every lazily provided
-- format (Excel, Numbers, Photoshop…) to render, which can block for seconds.
local MAIN = { "public.utf8-plain-text", "public.rtf", "public.html", "public.png", "public.tiff", "public.file-url" }

function P.save()
  if P.currentIsSecret() then return { secret = true } end
  local data = {}
  for _, t in ipairs(MAIN) do
    local v = hs.pasteboard.readDataForUTI(t)
    if v and #v > 0 then data[t] = v end
  end
  return { data = data }
end

-- A secret is not written back: re-writing it would give it a fresh changeCount and defeat the
-- password manager's auto-clear. The pasteboard is cleared instead.
function P.restore(saved)
  if not saved or saved.secret or not next(saved.data or {}) then
    hs.pasteboard.clearContents()
  else
    hs.pasteboard.writeAllData(saved.data)
  end
end

-- Calls cb(true) as soon as the pasteboard changes after `before`, or cb(false) after `timeout` s.
function P.waitChange(before, timeout, cb)
  local t0 = hs.timer.secondsSinceEpoch()
  local tmr
  tmr = hs.timer.doEvery(0.03, function()
    local changed = hs.pasteboard.changeCount() ~= before
    if changed or hs.timer.secondsSinceEpoch() - t0 > timeout then
      tmr:stop()
      Keep.live[tmr] = nil
      cb(changed)
    end
  end)
  Keep.live[tmr] = true
end

return P
